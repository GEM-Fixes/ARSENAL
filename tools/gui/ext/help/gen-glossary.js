// gen-glossary: build glossary-data.js (bundled in the exe) from guide/22-glossary.md and guide/i18n/<lang>/22-glossary.md.
// usage: node tools/gui/ext/help/gen-glossary.js [guideDir]   rerun after the glossary chapter changes; the help test checks the term count still matches.
// Author: Imperator_Aug (ARSENAL, ia-ea15f650)
'use strict';
const fs = require('fs'), path = require('path');
const GUIDE = path.resolve(process.argv[2] || path.join(__dirname, '..', '..', '..', '..', 'guide'));

// one md glossary -> [{t: term, d: plain definition, ch: ['08-infantry-and-humans.md', ..]}]
function parse(md) {
  const out = [];
  for (const l of md.split(/\r?\n/)) {
    const m = /^- \*\*(.+?)\*\*:?\s*(.*)$/.exec(l);
    if (!m) continue;
    const ch = [];
    const d = m[2].replace(/\[([^\]]*)\]\(([^)]*)\)/g, (a, txt, url) => { const f = /(\d\d-[a-z0-9-]+\.md)/.exec(url); if (f && !ch.includes(f[1])) ch.push(f[1]); return txt; })
      .replace(/`([^`]*)`/g, '$1').replace(/\*\*([^*]*)\*\*/g, '$1').replace(/^[:：]\s*/, '').trim();
    out.push({ t: m[1].replace(/`/g, '').replace(/[:：]$/, '').trim(), d, ch });
  }
  return out;
}
function build(guideDir) {
  const data = {};
  const en = path.join(guideDir, '22-glossary.md');
  data.en = parse(fs.readFileSync(en, 'utf8'));
  for (const c of ['ru', 'uk', 'zh']) {
    const f = path.join(guideDir, 'i18n', c, '22-glossary.md');
    data[c] = fs.existsSync(f) ? parse(fs.readFileSync(f, 'utf8')) : null;   // null = page shows English with a note
  }
  return data;
}
if (require.main === module) {
  const data = build(GUIDE);
  const out = path.join(__dirname, 'glossary-data.js');
  const body = '// generated by gen-glossary.js from guide/22-glossary.md (+ guide/i18n). Do not edit by hand: rerun the generator.\r\n' +
    "'use strict';\r\nmodule.exports = " + JSON.stringify(data) + ';\r\n';
  fs.writeFileSync(out, body);
  console.log('glossary-data.js: en ' + data.en.length + ', ' + ['ru', 'uk', 'zh'].map(c => c + ' ' + (data[c] ? data[c].length : 'none')).join(', '));
}
module.exports = { parse, build };
