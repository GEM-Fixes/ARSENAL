// macrostd step index: <modDir>/MACROS.md (ctx.opts.out, default MACROS.md; a file name at the mod root), CRLF.
//   One table per defining file (edited scope): macro, parameters (named %x, positional %0..), call sites in the mod (+ "vanilla" when
//   vanilla files call it too), owner, the first line of the comment block directly above the define. Bytes of comments kept (latin1).
// Author: Imperator_Aug (ARSENAL, ia-74ab23f5)
const cell = s => String(s).replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');

function render(m) {
  const by = new Map();
  for (const d of m.defines) if (d.scope) { if (!by.has(d.rel)) by.set(d.rel, []); by.get(d.rel).push(d); }
  const L = ['# Macros', '', `Generated by macrostd index. ${m.defines.filter(d => d.scope).length} defines in ${by.size} files. ` +
    'calls = literal call sites in this mod (macro bodies included); "+ vanilla" = vanilla files call it too. owner vanilla = the name is also vanilla\'s: do not rename.', ''];
  for (const rel of [...by.keys()].sort()) {
    L.push(`## ${rel}`, '', '| macro | parameters | calls | owner | line | description |', '|---|---|---|---|---|---|');
    for (const d of by.get(rel)) {
      const x = m.byName.get(d.name);
      const ps = [...d.params.named.map(p => '%' + p), ...d.params.positional.map(p => '%' + p)].join(' ') || '-';
      const calls = (x ? x.calls.length : 0) + (m.vanilla.called.has(d.name) ? ' + vanilla' : '');
      L.push(`| ${cell(d.name)} | ${cell(ps)} | ${calls} | ${d.owner} | ${d.line} | ${cell(d.desc || '')} |`);
    }
    L.push('');
  }
  return L.join('\r\n');
}

module.exports = {
  id: 'index',
  title: 'MACROS.md table of every macro the mod defines',
  render,
  plan(ctx) {
    const out = (ctx.opts && ctx.opts.out) || 'MACROS.md';
    if (/[\\/]/.test(out) || !/^(MACROS|README)[^/]*\.md$/i.test(out)) throw new Error('index --out must be a MACROS*.md / README*.md name at the mod root');
    const text = render(ctx.model);
    const old = ctx.exists(out) ? ctx.read(out).toString('latin1') : null;
    if (old === text) return { changes: [], cases: [] };
    return { changes: [{ file: out, after: Buffer.from(text, 'latin1'), create: old === null, rows: [{ line: 1, kind: old === null ? 'create' : 'rewrite', before: '', after: out, note: `${ctx.model.defines.filter(d => d.scope).length} defines` }] }], cases: [] };
  },
};
