function tier(n, word, v) {
  // n = first field number of this tier's three class-name copies
  const c = i => '@cls_' + (n + i) + '@';
  return [
    '(define "armor_' + c(0) + '_' + word + '"',
    '\t("armor_' + c(1) + '_areas" t(6) track_b(' + v.tb + ') bod(%body) tur(%turret) en(' + v.en + ') gun(' + v.gun + ') dur(@dur_' + word + '@) thr(@thr_' + word + '@) pierce_dur(999))',
    '\t("components_' + c(2) + '" repair(@repair_' + word + '@))',
    '',
    '\t{sensor',
    '\t\t{visor "view-around"',
    '\t\t\t{vision "none"}',
    '\t\t\t{bone "basis"}',
    '\t\t}',
    '\t\t{visor "main"',
    '\t\t\t{vision "@vision_' + word + '@"}',
    '\t\t}',
    '\t}',
    ')'];
}
