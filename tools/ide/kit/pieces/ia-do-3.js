// Fills the fields every piece of this group shares; each piece gets its own copies of the lists.
function p(o) {
  var x = { id: o.id, sec: o.sec, kinds: ['ia-entity'], scope: (o.scope || ACT).slice() };
  if (o.events) x.events = o.events.slice();
  x.role = 'act'; x.code = o.code; x.f = o.f || {};
  Object.keys(x.f).forEach(function (n) { if (x.f[n].choices) x.f[n].choices = x.f[n].choices.slice(); });
  x.needs = o.needs || []; x.tag = o.tag || 'V'; x.lim = o.lim || []; x.src = o.src; x.short = !!o.short;
  x.adv = x.tag === 'T'; x.wrap = false; x.task = null; x.since = '2026-11';
  return x;
}
