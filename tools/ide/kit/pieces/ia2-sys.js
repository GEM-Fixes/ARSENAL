// one ground effect file: name, optional first branch [tag, spawn lines]
function groundFile(name, first) {
  const chain = (first ? [first] : []).concat(GROUND_DETONATE);
  const out = [';SDL', '{"' + name + '"'].concat(GROUND_HIT, ['\t{on detonate']);
  chain.forEach((b, i) => {
    out.push('\t\t' + (i ? 'else' : '{if') + ' stuff "' + b[0] + '"');
    b[1].forEach(s => out.push('\t\t\t' + s));
  });
  out.push('\t\t}', '\t}', '}');
  return out.join('\n');
}

